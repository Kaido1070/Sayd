def place(path, name=""):
    """(القسم، الفئة) بأسماء قائمة إكسترا."""
    lab = label(path, name)
    return PLACE.get(lab, (OTHER, lab if lab != OTHER else OTHER))


def _key(s):
    return re.sub(r"\s+", "", _norm(s or ""))


def _pos(name, names):
    """موضع الاسم في قائمة إكسترا مع تجاوز فروق الإملاء البسيطة (ة/ه، المسافات، حرف ساقط في أوله)."""
    k = _key(name)
    for i, n in enumerate(names):
        m = _key(n)
        if k == m or (min(len(k), len(m)) >= 6 and (k.endswith(m) or m.endswith(k))):
            return i
    return len(names)


def order(menu, used):
    """ترتيب الأقسام وفئاتها كما في قائمة إكسترا (menu: [(قسم، [فئات])])، لما يُستخدم فقط.
    used: {قسم: {فئة,...}}. ما ليس في القائمة يأتي بعدها مرتباً بالاسم، و«أخرى» آخراً."""
    menu = menu or MENU
    depts = [d for d, _ in menu]
    subs = {_key(d): cs for d, cs in menu}
    rank = lambda d: (d == OTHER, _pos(d, depts), d)
    return [[d, sorted(used[d], key=lambda c: (c == OTHER, _pos(c, subs.get(_key(d), [])), c))]
            for d in sorted(used, key=rank)]
