def label(path, name=""):
    """الفئة الواضحة من مسار إكسترا «القسم > العائلة > الفئة» (أي جزء قد يكون ناقصاً) واسم المنتج."""
    n = _norm(name)
    for rx, lab, skip in NAME_RULES:
        if rx.search(n) and not (skip and skip.search(n)):
            return lab
    parts = [p.strip() for p in (path or "").split(">")]
    dept, family, leaf = (parts + ["", "", ""])[:3]
    for x in (leaf, family, dept):
        if x in LEAF:
            return LEAF[x]
    if (dept, family) in FAMILY_IN:
        return FAMILY_IN[(dept, family)]
    if family in FAMILY:
        return FAMILY[family]
    if dept in DEPT:
        return DEPT[dept]
    return family or dept or OTHER
