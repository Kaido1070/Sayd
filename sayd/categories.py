def _norm(s):
    s = re.sub("[\u064b-\u065f\u0640]", "", s or "")
    return s.translate(str.maketrans("أإآٱةى", "ااااهي"))


# أنواع يُعرف المنتج من اسمه بثقة (بعد التوحيد: ا بدل أإآ، ه بدل ة، ي بدل ى).
# (النمط، الفئة، استثناء) والأول المطابق يُعتمد
